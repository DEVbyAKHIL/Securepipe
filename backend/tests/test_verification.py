@pytest.mark.asyncio
async def test_gemini_specific_verification():
    """Gemini-specific verification: a log or response indicating whether the displayed guidance was generated by Gemini or by a fallback"""
    findings = [Finding(id="f1", scanner="test", severity=Severity.CRITICAL, title="Test", description="Test", file="test.py")]
    
    with patch("app.services.ai_suggestions.settings.AI_ENABLED", True):
        # Test Gemini success
        with patch("app.services.ai_suggestions.get_gemini_suggestion", return_value="Fix it!"):
            res1 = await enrich_all_findings(findings.copy())
            assert "Fix it!" in res1[0].suggestion
            
        # Test Fallback (Exception in Gemini)
        with patch("app.services.ai_suggestions.get_gemini_suggestion", side_effect=Exception("Gemini down")):
            res2 = await enrich_all_findings([Finding(id="f2", scanner="test", severity=Severity.CRITICAL, title="Test", description="Test", file="test.py")])
            assert "Immediate action required" in res2[0].suggestion

